"""Conservative local attribution gate; policy is opt-in for immutable replay."""
import re
from urllib.parse import urlsplit

from .publisher_scope import POLICY as REPOSITORY_POLICY
from .project_scope import POLICY as PROJECT_POLICY
from .project_documents import POLICY as DYNAMIC_POLICY
from .publisher_roles import POLICY as ROLE_POLICY
from .hosted_document_policy import POLICY

LEGACY_POLICY = 'explicit_attribution_v1'
POLICIES = (LEGACY_POLICY, REPOSITORY_POLICY, PROJECT_POLICY, DYNAMIC_POLICY, ROLE_POLICY, POLICY)
REASONS = {
    'title_only': '仅文档或产品标题，未证明发布方',
    'attribution_missing': '缺少具名发布、作者、维护或版权关系',
    'platform_credit': '仅建站平台或生成工具署名',
    'attribution_placeholder': '归属指向其他页面，尚未取得具名依据',
    'license_template_credit': '仅许可证模板署名，未证明项目发布方',
}


def enabled(goal):
    return goal.get('comparison', {}).get('publisher_policy') in POLICIES


def attribution_status(source, publisher, *, policy=None):
    """Called after literal name, occurrence and unique quotation checks.

    This proves a captured attribution assertion, not legal ownership. A model
    still reviews relevance and independence separately. Unknown forms fail shut.
    """
    quote = ' '.join(publisher['quote'].split())
    name = ' '.join(publisher['name'].split())
    if (policy in {PROJECT_POLICY, DYNAMIC_POLICY, ROLE_POLICY, POLICY} and 'free software foundation' in name.casefold()
            and re.search(r'GNU\s+(?:(?:AFFERO|LESSER)\s+)?GENERAL\s+PUBLIC\s+LICENSE',
                          source.get('text', ''), re.I)
            and re.search(r'©|\bcopyright\b', quote, re.I)):
        return 'license_template_credit'
    n = re.escape(name)
    if re.search(r'\b(?:created using|built with|powered by|generated by)\b', quote, re.I):
        return 'platform_credit'
    if re.search(r'\bsee\s+(?:authors|contributors|copyright)\b', quote, re.I):
        return 'attribution_placeholder'
    if re.search(r'\b(?:trademarks?|respective owners|permission is hereby granted|MIT license|licensed under)\b', quote, re.I):
        return 'attribution_missing'
    # Actual GitHub account/repository header is publication account evidence.
    url = urlsplit(source['url'])
    parts = url.path.strip('/').split('/')
    platform_name = re.sub(r'[^a-z]', '', name.casefold())
    if ((url.hostname == 'github.com' and len(parts) >= 2
         and platform_name in {'github', 'githubinc'})
            or (url.hostname and url.hostname.endswith('.readthedocs.io')
                and platform_name in {'readthedocs', 'readthedocsinc'})):
        return 'platform_credit'
    if (url.hostname == 'github.com' and len(parts) == 2 and name == parts[0]
            and quote == ' '.join(parts) and '\n' in publisher['quote']
            and '/'.join(parts).casefold() in source.get('title', '').casefold()):
        return 'supported'
    title = ' '.join(source.get('title', '').split())
    if any(quote.casefold() == part.strip().casefold()
           for part in [title, *re.split(r'[|·—–]', title)]):
        return 'title_only'
    if re.search(r'\b(?:not|never|neither|no longer)\b|并非|不是|不由|未经', quote, re.I):
        return 'attribution_missing'
    if policy in {ROLE_POLICY, POLICY}:
        from .publisher_roles import role
        if role(source, publisher, policy=policy):
            return 'supported'
    # Bind the claimed name directly to its role, rather than accepting a role
    # elsewhere in the quote (e.g. "Alice. Copyright Bob").
    role = r'(?:published|maintained|authored|written|created|started|founded|owned|operated)\s+by'
    label = r'(?:publisher|authors?|maintainers?|copyright holders?)\s*:'
    if re.search(r'(?:\b' + role + r'|\b' + label + r')\s+' + n + r'(?=$|[\s.,;:()])', quote, re.I):
        return 'supported'
    if re.fullmatch(r'(?:Publisher|Authors?|Maintainers?)\s+' + n + r'\.?', quote, re.I):
        return 'supported'
    if re.search(n + r'\s+(?:is|became|serves as)\s+(?:the\s+|a\s+)?(?:co-)?maintainer\s+of\s+(?:this|the)\s+project\b', quote, re.I):
        return 'supported'
    if re.search(r'(?:©|\bcopyright\b)\s*(?:\(c\)\s*)?(?:[0-9]{4}(?:\s*[-–,]\s*[0-9]{4})?\s*[,.:]?\s*)?' + n + r'(?=$|[\s.,;:()])', quote, re.I):
        return 'supported'
    if re.fullmatch(r'@?' + n + r',\s*All rights reserved\.?', quote, re.I):
        return 'supported'
    if re.fullmatch(r'@' + n + r',\s*[^.;\n]{1,100}\b(?:Limited|Ltd\.?|Inc\.?|LLC),\s*All rights reserved\.?', quote, re.I):
        return 'supported'
    if re.search(r'(?:发布方|作者|维护者|版权所有)\s*[：:]?\s*' + n + r'(?:$|[\s，。；])', quote):
        return 'supported'
    if re.fullmatch(n + r'(?:\s+v?[\d.]+)?\s+(?:documentation|docs|manual|文档)', quote, re.I):
        return 'title_only'
    return 'attribution_missing'


def review_instructions(goal):
    if not enabled(goal):
        return ''
    instructions = (' This task enforces explicit named attribution locally. Document titles, '
            'product/version headings, platform credits, and See AUTHORS placeholders cannot pass. '
            'Read the supplied AUTHORS/maintainer text even when it has no dimension quote. '
            'An explicit sentence that this project was started/founded by a named person, '
            'or that a named person became co-maintainer of the project, IS project attribution. '
            'Select that person as name and the exact sentence as quote; do not omit a named '
            'project maintainer merely because the schema calls this field publisher. '
            'This records the captured statement, not legal ownership or proof that a fork '
            'is official. Keep mirrors/forks/translations of the same project in one group. '
            'A GitHub repository account header requires the actual account/repository '
            'header matching the exact repository URL; a URL or page title alone is insufficient.')

    if goal.get('comparison', {}).get('publisher_policy') == REPOSITORY_POLICY:
        instructions += (' Publisher support on GitHub cannot cross owner/repository boundaries. '
                         'Account profiles, other repositories, platform pages and raw/API hosts '
                         'cannot attribute this repository. Links alone do not prove identity. '
                         'Use evidence within the same repository; unsupported hosting platforms '
                         'require attribution on each page itself.')
    if goal.get('comparison', {}).get('publisher_policy') in {PROJECT_POLICY, DYNAMIC_POLICY, ROLE_POLICY, POLICY}:
        instructions += (' Publisher support cannot cross project boundaries on hosted platforms. '
                         'GitLab includes the full nested namespace; Hugging Face includes model, '
                         'dataset or space type plus owner/repository; Codeberg and GitHub include '
                         'owner/repository. Other projects of the same account cannot supply identity. '
                         'Platform credits, paper citations and license-template authors do not '
                         'establish the project publisher. Links and URL structure are not identity '
                         'evidence. Unknown project scopes require explicit attribution on that page.')
    if goal.get('comparison', {}).get('publisher_policy') in {ROLE_POLICY, POLICY}:
        candidate_output = (
            'For THIS policy override the previous publisher output shape on sources with '
            'nonempty candidates: publisher MUST be null or {"candidate_index":0} (or 1), '
            'indexing that source\'s project_role_candidates list. Never rewrite its name '
            'or quote. The runtime expands your selected index to the exact named evidence. '
            'For sources with no candidates retain the original name/quote schema. '
            if goal.get('comparison', {}).get('evidence_version') == 4 else
            'Retain the original publisher name/quote schema: if a candidate is valid, '
            'copy its exact name and quote only, omitting its role field. ')
        instructions += (' Distinguish project authors and maintainers from exclusive publishers. '
                         'In a captured AUTHORS roster, select a complete unique name line with '
                         'its heading or an adjacent complete member line as one literal quote. '
                         'For narrative roles, select the full explicit sentence binding the '
                         'person to this project. Different coauthors/maintainers of that same '
                         'project can coexist; never treat them as independent publishers. '
                         'A generic article byline, paper citation or copyright holder alone '
                         'does not establish this nonexclusive project role. '
                         'Each source may include project_role_candidates: locally matched '
                         'literal role suggestions, not trusted ownership or independence verdicts. '
                         'Review them against the supplied source. ' + candidate_output +
                         'An AUTHORS roster headed AUTHORS '
                         'in this project IS explicit named project authorship, even without a '
                         'company/publisher label. If valid, select one named candidate; '
                         'do not leave it null because authorship is not legal '
                         'ownership. Prefer the shortest complete candidate sentence over adding '
                         'a second person\'s sentence to its quote.')
    if goal.get('comparison', {}).get('publisher_policy') == POLICY:
        instructions += (' Read the Docs hosts distinct projects at distinct project subdomains; '
                         'sharing readthedocs.io is not evidence of common publication. '
                         'Still group translations, forks, mirrors and same-project pages together. '
                         'A complete standalone Author/Authors field naming people is explicit '
                         'documentation project authorship, including when label, colon and names '
                         'appear on separate lines. Review these literal candidates even on pages '
                         'with no dimension quotation. Use candidate_index when candidates exist; '
                         'do not infer authorship from the page title, hosting provider or URL. '
                         'Evidence cannot transfer across project subdomains or /projects/ aliases.')
    from .comparison_repair import enabled as repair_policy
    if repair_policy(goal):
        instructions += (' Inspect captured copyright and All rights reserved lines, '
                         'including pages without dimension quotes. A unique complete '
                         'line such as "@Atlas, Example Education Private Limited, All rights reserved" '
                         'is explicit publication attribution when it actually occurs '
                         'in the supplied text. For that pattern use the publication '
                         'name immediately after @ and before the first comma '
                         '(Atlas in this example), preserving the whole line as quote; '
                         'do not substitute another name occurring later in the line. '
                         'Keep the existing candidate_index protocol for sources with '
                         'nonempty project_role_candidates; name/quote applies only '
                         'where that protocol permits it. '
                         'This generic publisher/copyright evidence is distinct from '
                         'a nonexclusive project author/maintainer role and need not '
                         'qualify as such a role. Do not copy this illustrative example, '
                         'infer identity from names or titles, invent attribution, or '
                         'treat distinct pages of the same publication as independent. '
                         'If no valid literal attribution exists, retain null.')
    if goal.get('comparison', {}).get('dimension_routing') == 6:
        instructions += (' A literal documentation footer such as '
                         '"© Copyright 2020-2026, Example Person." explicitly attributes '
                         'that publication to Example Person; use the actual captured '
                         'name and complete unique copyright line, never this example. '
                         'This is ordinary publication attribution, not a claim of '
                         'nonexclusive project authorship or legal ownership. It need '
                         'not match a project_role_candidate. Where that list is empty '
                         'use the original name/quote schema; never omit a valid footer '
                         'solely because the page has no relevant dimension span. '
                         'Do not assign software-tool/theme/platform credits to the '
                         'publication. Null remains required when attribution is absent.')
    return instructions
